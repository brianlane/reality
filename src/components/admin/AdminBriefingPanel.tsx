"use client";

import { useCallback, useEffect, useState } from "react";
import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { getAuthHeaders } from "@/lib/supabase/auth-headers";

type BriefingContent = {
  faultLines?: Array<{ title: string; detail: string }>;
  threads?: Array<{ prompt: string; why: string }>;
  guidance?: string;
};

type Briefing = {
  id: string;
  audience: "CURATOR" | "APPLICANT";
  content: unknown;
  matchId: string | null;
  model: string | null;
  createdAt: string;
  agentProfile: { id: string; version: number; depth: string } | null;
};

function renderContent(content: unknown) {
  const c = (content ?? {}) as BriefingContent;
  const hasStructured =
    (c.faultLines?.length ?? 0) > 0 ||
    (c.threads?.length ?? 0) > 0 ||
    !!c.guidance;

  if (!hasStructured) {
    return (
      <pre className="whitespace-pre-wrap text-xs text-navy-soft">
        {JSON.stringify(content, null, 2)}
      </pre>
    );
  }

  return (
    <div className="space-y-3 text-sm">
      {c.guidance && (
        <p className="text-navy-soft">
          <span className="font-medium text-navy">Guidance: </span>
          {c.guidance}
        </p>
      )}
      {c.faultLines && c.faultLines.length > 0 && (
        <div>
          <p className="font-medium text-navy">Fault lines</p>
          <ul className="mt-1 list-inside list-disc space-y-1 text-navy-soft">
            {c.faultLines.map((f, i) => (
              <li key={i}>
                <span className="font-medium text-navy">{f.title}:</span>{" "}
                {f.detail}
              </li>
            ))}
          </ul>
        </div>
      )}
      {c.threads && c.threads.length > 0 && (
        <div>
          <p className="font-medium text-navy">Conversation threads</p>
          <ul className="mt-1 list-inside list-disc space-y-1 text-navy-soft">
            {c.threads.map((t, i) => (
              <li key={i}>
                <span className="font-medium text-navy">{t.prompt}</span>
                {t.why && <span> — {t.why}</span>}
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}

/**
 * Curator-facing panel on the application detail page. Lists the agent
 * briefings generated for this applicant. Generation itself is a later PR;
 * until then this panel shows an empty state so curators know the feature
 * is coming.
 */
export default function AdminBriefingPanel({
  applicantId,
}: {
  applicantId: string;
}) {
  const [briefings, setBriefings] = useState<Briefing[] | null>(null);
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(async () => {
    setError(null);
    try {
      const headers = await getAuthHeaders();
      if (!headers) return;
      const res = await fetch(
        `/api/admin/applicants/${applicantId}/briefings`,
        { headers },
      );
      if (!res.ok) throw new Error("Failed to load briefings");
      const json = await res.json();
      setBriefings(json.briefings ?? []);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed to load briefings");
    }
  }, [applicantId]);

  useEffect(() => {
    void load();
  }, [load]);

  return (
    <Card>
      <div className="flex items-center justify-between">
        <div>
          <h2 className="text-lg font-semibold text-navy">Agent Briefings</h2>
          <p className="mt-1 text-sm text-navy-soft">
            Compatibility briefings generated by the applicant&apos;s agent.
          </p>
        </div>
        <Button variant="outline" onClick={() => void load()}>
          Refresh
        </Button>
      </div>

      <div className="mt-4">
        {error && <p className="text-sm text-red-600">{error}</p>}
        {!error && briefings === null && (
          <p className="text-sm text-navy-soft">Loading…</p>
        )}
        {!error && briefings !== null && briefings.length === 0 && (
          <p className="text-sm text-navy-soft">
            No briefings yet. Briefings are generated once the agent pipeline is
            live.
          </p>
        )}
        {!error &&
          briefings !== null &&
          briefings.map((b) => (
            <div key={b.id} className="border-t py-4 first:border-t-0">
              <div className="flex flex-wrap items-center gap-2 text-xs text-navy-soft">
                <span className="font-medium text-navy">{b.audience}</span>
                {b.matchId && <span>Match {b.matchId.slice(0, 8)}</span>}
                {b.agentProfile && (
                  <span>
                    Profile v{b.agentProfile.version} · {b.agentProfile.depth}
                  </span>
                )}
                {b.model && <span>{b.model}</span>}
                <span>{new Date(b.createdAt).toLocaleString()}</span>
              </div>
              <div className="mt-2">{renderContent(b.content)}</div>
            </div>
          ))}
      </div>
    </Card>
  );
}
